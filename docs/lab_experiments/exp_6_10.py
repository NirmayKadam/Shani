def _code_size():
    exts = (".py", ".js", ".html", ".css")
    skip = ("node_modules", "legacy", "__pycache__", ".git", "venv", "lab_experiments")
    files = lines = 0
    for root, dirs, fs in os.walk(REPO):
        dirs[:] = [x for x in dirs if x not in skip and not x.startswith(".")]
        for f in fs:
            if f.endswith(exts):
                try:
                    with open(os.path.join(root, f), encoding="utf-8", errors="ignore") as fh:
                        lines += sum(1 for _ in fh)
                    files += 1
                except OSError:
                    pass
    return files, lines


