# ----------------------------------------------------------------------------- LaTeX helpers

def latex_to_text(s: str, numbers: dict) -> str:
    s = re.sub(r"\\(" + "|".join(sorted(numbers, key=len, reverse=True)) + r")(\{\})?",
               lambda m: numbers[m.group(1)], s)
    for cmd, sym in {"\\kappa": "κ", "\\epsilon_t": "ε", "\\epsilon": "ε", "\\delta": "δ", "\\sigma": "σ",
                     "\\leq": "≤", "\\geq": "≥", "\\le": "≤", "\\ge": "≥", "\\times": "×"}.items():
        s = s.replace(cmd, sym)
    s = s.replace("\\%", "%").replace("~", " ").replace("---", "—").replace("--", "–").replace("$", "")
    s = re.sub(r"\\emph\{([^}]*)\}", r"\1", s)
    s = re.sub(r"\\textbf\{([^}]*)\}", r"\1", s)
    s = s.replace("\\&", "&")
    return re.sub(r"\s+", " ", s).strip()


def paper_parts(numbers: dict):
    tex = open(os.path.join(REPO, "research", "paper", "main.tex"), encoding="utf-8").read()
    abstract = re.search(r"\\begin\{abstract\}(.*?)\\end\{abstract\}", tex, re.S).group(1)
    sections = re.findall(r"\\section\{([^}]*)\}", tex)
    tables = re.findall(r"\\input\{\\outdir/tables/([^}]*)\.tex\}", tex)
    figures = re.findall(r"\\includegraphics\[[^\]]*\]\{([^}]*)\}", tex)
    refs = len(re.findall(r"\\bibitem\{", tex))
    fillins = [latex_to_text(f, numbers) for f in re.findall(r"\\fillin\{([^}]*)\}", tex)]
    return latex_to_text(abstract, numbers), sections, tables, figures, refs, fillins


